DROP TABLE IF EXISTS cities CASCADE;

CREATE TABLE cities (
    id INT PRIMARY KEY,
    city VARCHAR(50)
);

CREATE TABLE restaurant_type (
    id INT PRIMARY KEY,
    restaurant_type VARCHAR(20)
);

CREATE TABLE serve_type (
    id INT PRIMARY KEY,
    serve_type VARCHAR(20)
);

CREATE TABLE meal_types (
    id INT PRIMARY KEY,
    meal_type VARCHAR(20)
);

CREATE TABLE restaurant (
    id INT PRIMARY KEY,
    restaurant_name VARCHAR(50),
    restaurant_type_id INT REFERENCES restaurant_type(id),
    income_percentage NUMERIC(5,2),
    city_id INT REFERENCES cities(id)
);

CREATE TABLE meals (
    id INT PRIMARY KEY,
    restaurant_id INT REFERENCES restaurant(id),
    serve_type_id INT REFERENCES serve_type(id),
    meal_type_id INT REFERENCES meal_types(id),
    hot_cold VARCHAR(10) CHECK (hot_cold IN ('Hot', 'Cold')),
    meal_name VARCHAR(50),
    price NUMERIC(10,2)
);

CREATE TABLE members (
    id INT PRIMARY KEY,
    first_name VARCHAR(50),
    surname VARCHAR(50),
    sex CHAR(1) CHECK (sex IN ('M','F')),
    email VARCHAR(50),
    city_id INT REFERENCES cities(id),
    monthly_budget NUMERIC(10,2)
);

CREATE TABLE orders (
    id INT PRIMARY KEY,
    order_timestamp TIMESTAMP,
    member_id INT REFERENCES members(id),
    restaurant_id INT REFERENCES restaurant(id),
    total_order NUMERIC(10,2)
);

CREATE TABLE order_details (
    id INT PRIMARY KEY,
    order_id INT REFERENCES orders(id),
    meal_id INT REFERENCES meals(id)
);

CREATE TABLE monthly_members (
    member_id INT PRIMARY KEY,
    first_name VARCHAR(50),
    surname VARCHAR(50),
    sex CHAR(1) CHECK (sex IN ('M', 'F')),
    email VARCHAR(50),
    city VARCHAR(50),
    year INT,
    month INT,
    order_count INT,
    meals_count INT,
    monthly_budget NUMERIC(10,2),
    total_expense NUMERIC(10,2),
    balance NUMERIC(10,2),
    commission NUMERIC(10,2)
);

