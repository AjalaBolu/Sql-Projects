-- Categorize orders into Small (< $20), Medium ($20-$50), Large (> $50) using CASE.
select *,
	case
		when total_order < 20 then 'small'
		when total_order between 21 and 50 then 'medium'
		else 'large'
	end as order_category
from orders;

-- 	Segment members by total spend into High value (> $500), Medium, Low.
select 
	M.first_name,
	M.surname,
	sum(O.total_order) as total_spend,
	case
		when sum(O.total_order) > 500 then 'High'
		when sum(O.total_order) between 500 and 200 then 'Medium'
		else 'Low'
	end as Member_segment
from orders O
join members M
	on O.member_id = M.id
group by M.first_name,M.surname;

-- Classify meals as budget (< $20), standard ($20-$50), or premium (> $50) based on price.
select 
	meal_name,
	price,
	case
		when price < 20 then 'Budget'
		when price between 20 and 50 then 'Standard'
		else 'Premium'
	end as meal_category
from meals;

-- Label restaurants by income_percentage as low, mid, or high commission.
select *,
	case 
		when income_percentage < 5 then 'Low'
		when income_percentage  < 10 then 'Mid'
		else 'High'
	end as commission
from restaurant;

