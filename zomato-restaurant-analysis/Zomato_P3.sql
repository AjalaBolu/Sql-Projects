/*
	Level 7 — Window Functions
	1.	Rank restaurants based on total revenue.
	2.	Find the top 3 restaurants in each city using ROW_NUMBER.
	3.	Show the previous order amount for each member using LAG.
	4.	Calculate the difference in total_order between consecutive orders for a member.
	5.	Identify the member with the highest spend per city.
	Skills: ROW_NUMBER()  •  RANK()  •  DENSE_RANK()  •  LAG()  •  LEAD()
*/

-- Rank restaurants based on total revenue.
select 
	restaurant_id ,
	sum(total_order) as total_spend,
	rank() over (order by sum(total_order) desc ) as total_rank
from orders
group by restaurant_id;

-- Find the top 3 restaurants in each city using ROW_NUMBER.
SELECT *
FROM (
    SELECT 
        R.restaurant_name,
        C.city,
        COUNT(O.id) AS total_orders,
        ROW_NUMBER() OVER (
            PARTITION BY R.city_id 
            ORDER BY COUNT(O.id) DESC
        ) AS rank
    FROM restaurant R
    JOIN orders O ON R.id = O.restaurant_id
    JOIN cities C ON R.city_id = C.id
    GROUP BY R.id, R.restaurant_name, R.city_id, C.city
) AS ranked
WHERE rank <= 3;

-- Show the previous order amount for each member using LAG.
SELECT 
    id,
    member_id,
    order_timestamp,
    total_order,
    LAG(total_order) OVER (
        PARTITION BY member_id 
        ORDER BY order_timestamp
    ) AS previous_order
FROM orders;

-- Calculate the difference in total_order between consecutive orders for a member.
SELECT 
    id as order_id, 
    member_id,
    order_timestamp,
    total_order,
    LAG(total_order) OVER (
        PARTITION BY member_id 
        ORDER BY order_timestamp
    ) AS previous_order,
    total_order - LAG(total_order) OVER (
        PARTITION BY member_id 
        ORDER BY order_timestamp
    ) AS difference
FROM orders;


