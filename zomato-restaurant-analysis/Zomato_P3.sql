/*
	Level 8 — Real Business Problems
	1.	Identify the top 10 most loyal members by order count.
	2.	Find restaurants with declining order trends over time.
	3.	Find the member with the highest total spend per month.
	4.	Calculate customer lifetime value (CLV) using total spend per member.
	5.	Detect members at risk of churn (no orders in the last 90 days).
	6.	Find which restaurant type generates the most revenue.
	Skills: CTEs  •  Window functions  •  Date arithmetic  •  Aggregations
*/

-- Identify the top 10 most loyal members by order count.

SELECT 
    M.id,
    M.first_name,
    M.surname,
    COUNT(O.id) AS total_orders
FROM members M
JOIN orders O ON M.id = O.member_id
GROUP BY M.id, M.first_name, M.surname
ORDER BY total_orders DESC
LIMIT 10;

-- Find restaurants with declining order trends over time.
select *
from (
		SELECT 
		    R.restaurant_name,
		    EXTRACT(MONTH FROM O.order_timestamp) AS month,
		    SUM(O.total_order) AS current_orders,
		    LEAD(SUM(O.total_order)) OVER (
		        PARTITION BY R.id 
		        ORDER BY EXTRACT(MONTH FROM O.order_timestamp)
		    ) AS next_month_orders
		FROM restaurant R
		JOIN orders O ON R.id = O.restaurant_id
		GROUP BY R.id, R.restaurant_name, EXTRACT(MONTH FROM O.order_timestamp)
	)as trends
where next_month_orders < current_orders;

-- Find the member with the highest total spend per month.
SELECT * FROM (
    SELECT 
        M.id AS member_id,
        M.first_name,
        M.surname,
        EXTRACT(MONTH FROM order_timestamp) AS month,
        SUM(O.total_order) AS total_spend,
        ROW_NUMBER() OVER (
            PARTITION BY EXTRACT(MONTH FROM order_timestamp) 
            ORDER BY SUM(O.total_order) DESC
        ) AS rnk
    FROM members M
    JOIN orders O ON M.id = O.member_id
    GROUP BY M.id, M.first_name, M.surname, EXTRACT(MONTH FROM order_timestamp)
) AS ranked
WHERE rnk = 1;

-- Calculate customer lifetime value (CLV) using total spend per member.
select 
	m.id as member_id,
	m.first_name,
	m.surname,
	sum(o.total_order) as lifetime_value
from members as  m
	join orders as o
		on m.id = o.member_id
group by m.id, m.first_name, m.surname
order by lifetime_value desc;

-- Detect members at risk of churn (no orders in the last 90 days).
select 
	m.id as member_id,
	m.first_name,
	m.surname
from members m
join orders o
on m.id = o.member_id
where m.id not in(
	select distinct member_id
	from orders
	where order_timestamp >= '2020-07-31'::date - INTERVAL '90 days' );

