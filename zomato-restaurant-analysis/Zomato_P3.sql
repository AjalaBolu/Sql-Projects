select 
	R.id,
	R.restaurant_name,
	sum(O.total_order) AS total_revenue
from restaurant AS R
	join orders AS O
	on R.id = O.restaurant_id
group by R.id;

-- Find the average order value per member.
select 
	M.first_name,
	M.surname,
	round(avg(O.total_order), 2) as avg_order_value
from members as M
	join orders O
	on M.id = O.member_id
group by M.first_name, M.surname,M.id;

