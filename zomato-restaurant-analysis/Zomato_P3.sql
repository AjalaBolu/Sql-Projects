order by month;

/*
	Level 5 — Conditional Logic & Segmentation
	1.	Categorize orders into Small (< $20), Medium ($20-$50), Large (> $50) using CASE.
	2.	Segment members by total spend into High value (> $500), Medium, Low.
	3.	Classify meals as budget (< $20), standard ($20-$50), or premium (> $50) based on price.
	4.	Label restaurants by income_percentage as low, mid, or high commission.
	Skills: CASE WHEN
