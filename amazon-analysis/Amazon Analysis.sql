/*
11. Top Performing Sellers
Find the top 5 sellers based on total sales value.
Challenge: Include both successful and failed orders, and display their percentage of successful orders.
*/

WITH tps AS (
    SELECT 
        s.seller_id,
        s.seller_name,
        COUNT(DISTINCT o.order_id) AS total_orders,
        COUNT(DISTINCT CASE WHEN o.order_status = 'Completed' THEN o.order_id END)                          AS successful_orders,
        ROUND(SUM(oi.quantity * oi.price_per_unit)::NUMERIC, 2) AS total_sales
    FROM sellers s
    JOIN orders o
        ON s.seller_id = o.seller_id
    JOIN order_items oi
        ON oi.order_id = o.order_id
    GROUP BY 1, 2
)
SELECT 
    seller_name,
    total_orders,
    successful_orders,
    total_sales,
    ROUND((successful_orders * 100.0 / total_orders)::NUMERIC, 2)                                                                   AS success_pct,
    DENSE_RANK() OVER (ORDER BY total_sales DESC) AS rnk
FROM tps
ORDER BY rnk
LIMIT 5;
	
