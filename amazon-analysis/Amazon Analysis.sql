/*
1. Top Selling Products
Query the top 10 products by total sales value.
Challenge: Include product name, total quantity sold, and total sales value.
*/
SELECT 
    p.product_name,
    SUM(o.quantity)  AS quantity_sold,
    SUM(o.quantity * o.price_per_unit) AS total_sales
FROM products p
JOIN order_items o
    ON p.product_id = o.product_id
GROUP BY 1
ORDER BY 3 DESC
LIMIT 10;


/*
2. Revenue by Category
Calculate total revenue generated by each product category.
Challenge: Include the percentage contribution of each category to total revenue.
*/
SELECT 
    c.category_name,
    round (SUM(o.quantity * o.price_per_unit)::Numeric , 2)   AS total_revenue,
    ROUND(
        (SUM(o.quantity * o.price_per_unit) * 100.0 /
        (SELECT SUM(quantity * price_per_unit) FROM order_items))::NUMERIC , 2)   AS revenue_pct
FROM category c
JOIN products p
    ON c.category_id = p.category_id
JOIN order_items o
    ON p.product_id = o.product_id
GROUP BY 1
ORDER BY 2 DESC;


/*
3. Average Order Value (AOV)
Compute the average order value for each customer.
Challenge: Include only customers with more than 5 orders.
*/
with lt as 
(
	
	select 
		O.customer_id,
		c.first_name,
		round (avg(oi.quantity * oi.price_per_unit)::Numeric , 2) as aov
	from customers C
		 join orders O
			on C.customer_id = O.customer_id
		join order_items oi
			on O.order_id = oi.order_id
	where o.customer_id in 
		( 
			select 
				customer_id
			from orders 
			group by 1
			having count(*) > 5
		)
	group by 1,2
	order by 3 desc
	
) select * from lt;

/*
4. Monthly Sales Trend
Query monthly total sales over the past year.
Challenge: Display the sales trend, grouping by month, return current_month sale, last month sale!
*/
with monthly_sales as
(
	select 
		extract (year from order_date ) as year,
		extract (month from order_date ) as month,
		round (SUM(oi.quantity * oi.price_per_unit)::Numeric , 2)   AS current_month
	from orders as o
		join order_items as oi
			on o.order_id = oi.order_id
	group by 1, 2
	order by 1, 2 
) 
select 
	year,
	month,
	current_month,
	lag(current_month, 1) over (order by year, month) as last_month,
	ROUND(
        current_month - LAG(current_month, 1) OVER (ORDER BY year, month)
    , 2) AS mon_change 
	from monthly_sales;
	
