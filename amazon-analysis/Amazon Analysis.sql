-- TABLE 1: category

CREATE TABLE category (
    category_id     INT PRIMARY KEY,
    category_name   VARCHAR(20) NOT NULL
);


-- TABLE 2: customers

CREATE TABLE customers (
    customer_id     INT PRIMARY KEY,
    first_name      VARCHAR(20) NOT NULL,
    last_name       VARCHAR(20) NOT NULL,
    state           VARCHAR(20),
    address         VARCHAR(5) DEFAULT 'xxxx'
);


-- TABLE 3: sellers

CREATE TABLE sellers (
    seller_id       INT PRIMARY KEY,
    seller_name     VARCHAR(25) NOT NULL,
    origin          VARCHAR(15)
);


-- TABLE 4: products
CREATE TABLE products (
    product_id      INT PRIMARY KEY,
    product_name    VARCHAR(50) NOT NULL,
    price           FLOAT       NOT NULL CHECK (price >= 0),
    cogs            FLOAT       NOT NULL CHECK (cogs >= 0),
    category_id     INT,
    CONSTRAINT fk_product_category
        FOREIGN KEY (category_id)
        REFERENCES category (category_id)
);


-- TABLE 5: orders
CREATE TABLE orders (
    order_id        INT PRIMARY KEY,
    order_date      DATE        NOT NULL,
    customer_id     INT         NOT NULL,
    seller_id       INT         NOT NULL,
    order_status    VARCHAR(15) DEFAULT 'Pending',
    CONSTRAINT fk_orders_customer
        FOREIGN KEY (customer_id)
        REFERENCES customers (customer_id),
    CONSTRAINT fk_orders_seller
        FOREIGN KEY (seller_id)
        REFERENCES sellers (seller_id)
);

-- TABLE 6: order_items
CREATE TABLE order_items (
    order_item_id   INT PRIMARY KEY,
    order_id        INT         NOT NULL,
    product_id      INT         NOT NULL,
    quantity        INT         NOT NULL CHECK (quantity > 0),
    price_per_unit  FLOAT       NOT NULL CHECK (price_per_unit >= 0),
    CONSTRAINT fk_oi_order
        FOREIGN KEY (order_id)
        REFERENCES orders (order_id),
    CONSTRAINT fk_oi_product
        FOREIGN KEY (product_id)
        REFERENCES products (product_id)
);


-- TABLE 7: payments
CREATE TABLE payments (
    payment_id          INT PRIMARY KEY,
    order_id            INT         NOT NULL,
    payment_date        DATE,
    payment_status      VARCHAR(20) DEFAULT 'Pending',
    CONSTRAINT fk_payments_order
        FOREIGN KEY (order_id)
        REFERENCES orders (order_id)
);


-- TABLE 8: shippings

CREATE TABLE shippings (
    shipping_id         INT PRIMARY KEY,
    order_id            INT         NOT NULL,
    shipping_date       DATE,
    return_date         DATE,
    shipping_providers  VARCHAR(15),
    delivery_status     VARCHAR(15) DEFAULT 'Pending',
    CONSTRAINT fk_shippings_order
        FOREIGN KEY (order_id)
        REFERENCES orders (order_id)
);


-- TABLE 9: inventory

CREATE TABLE inventory (
    inventory_id    INT PRIMARY KEY,
    product_id      INT         NOT NULL,
    stock           INT         NOT NULL DEFAULT 0 CHECK (stock >= 0),
    warehouse_id    INT,
    last_stock_date DATE,
    CONSTRAINT fk_inventory_product
        FOREIGN KEY (product_id)
        REFERENCES products (product_id)
);

